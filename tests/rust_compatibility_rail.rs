fn json_array_contains(value: &Value, expected: &str) -> bool {
    value.as_array().is_some_and(|items| items.iter().any(|item| item.as_str() == Some(expected)))
}

fn assert_matrix_binding(cargo_mode: &Value, expected_status: &str, expected_class: &str) {
    let matrix = cargo_mode.get("compatibility_surface_matrix").expect("cargo mode should include matrix binding");
    assert_eq!(matrix["matrix_id"], MATRIX_ID);
    assert_eq!(matrix["matrix_path"], MATRIX_PATH);
    assert_eq!(matrix["status"], expected_status);
    assert_eq!(matrix["evidence_class"], expected_class);
    assert!(json_array_contains(&matrix["non_claims"], "not-full-cargo-compatibility"));
}

fn unit_plan_claim_violations(matrix: &Value) -> Vec<String> {
    let surfaces = matrix["surfaces"].as_array().expect("evaluated Rust compatibility surfaces");
    let mut issues = Vec::new();
    for surface in surfaces {
        if surface["unit_plan"]["status"] != "supported" {
            continue;
        }
        let row = surface["id"].as_str().expect("surface id");
        let non_claims = &surface["non_claims"];
        if !json_array_contains(non_claims, "not-full-cargo-compatibility") {
            issues.push(format!("supported unit_plan row `{row}` lacks full Cargo non-claim"));
        }
        if row == "native-link-metadata" && !json_array_contains(non_claims, "not-native-link-probing-correctness") {
            issues.push(format!("supported unit_plan row `{row}` lacks native probing non-claim"));
        }
        for overclaim in [
            "full-cargo-compatibility",
            "compiler-correctness",
            "release-eligibility",
        ] {
            if json_array_contains(non_claims, overclaim) {
                issues.push(format!("supported unit_plan row `{row}` makes overclaim `{overclaim}`"));
            }
        }
    }
    issues
}

#[test]
fn supported_unit_plan_matrix_rows_retain_bounded_non_claims() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let matrix: Value = crunch_eval::evaluate_and_deserialize(&root.join(MATRIX_PATH), &[]).unwrap();
    let issues = unit_plan_claim_violations(&matrix);
    assert!(issues.is_empty(), "unit plan claim drift: {}", issues.join("; "));

    let unbounded = serde_json::json!({"surfaces": [{
        "id": "native-link-metadata",
        "unit_plan": {"status": "supported"},
        "non_claims": ["full-cargo-compatibility"]
    }]});
    assert_eq!(unit_plan_claim_violations(&unbounded), [
        "supported unit_plan row `native-link-metadata` lacks full Cargo non-claim",
        "supported unit_plan row `native-link-metadata` lacks native probing non-claim",
        "supported unit_plan row `native-link-metadata` makes overclaim `full-cargo-compatibility`",
    ]);
}

#[test]
fn unit_plan_matrix_rejects_supported_rows_without_named_fixture() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join(MATRIX_PATH);
    let import = format!("import {}", serde_json::to_string(path.to_str().unwrap()).unwrap());
    let matrix: Value = crunch_eval::evaluate_str_and_deserialize(&import, &[]).unwrap();
    let row = matrix["surfaces"]
        .as_array()
        .unwrap()
        .iter()
        .find(|row| row["id"] == "path-workspace-basic")
        .unwrap();
    assert_eq!(row["unit_plan"]["status"], "supported");

    for fixtures in ["[]", "[\"\"]", "[\" \\t\"]"] {
        let expression = format!(
            "let matrix = {import} in matrix & {{ surfaces | force = \
             [(std.array.at 0 matrix.surfaces) & {{ unit_plan.fixtures | force = {fixtures} }}] }}"
        );
        let result: Result<Value, _> = crunch_eval::evaluate_str_and_deserialize(&expression, &[]);
        let error = result.expect_err("production matrix contract must reject an unnamed fixture").to_string();
        assert!(error.contains("path-workspace-basic"), "rejection must identify the row: {error}");
        assert!(error.contains("requires a named passing fixture"), "wrong rejection: {error}");
    }
}

#[test]
fn native_path_only_surface_reports_matrix_binding_without_cargo_fallback() {
    let fixture = tempfile::tempdir().unwrap();
    let shim_dir = tempfile::tempdir().unwrap();
    write_native_supported_workspace(fixture.path());
    let shim = shim_dir.path().join("cargo");
    std::fs::write(&shim, FAILING_CARGO_SHIM).unwrap();
    make_executable(&shim);

    let output = mantle_cmd()
        .arg("--json")
        .arg("rust-plan")
        .arg("--root")
        .arg(fixture.path())
        .arg("--cargo")
        .arg(&shim)
        .arg("--no-cargo-oracle")
        .output()
        .expect("mantle rust-plan should execute");
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);

    assert!(output.status.success(), "stdout:\n{stdout}\nstderr:\n{stderr}");
    assert!(!stderr.contains("cargo must not be invoked"), "rust-plan fell back to Cargo: {stderr}");
    let receipt: Value = serde_json::from_str(&stdout).expect("rust-plan JSON receipt");
    let cargo_mode = receipt.get("cargo_mode").expect("cargo_mode exists");
    assert_eq!(cargo_mode["compatibility_class"], "cargo-free-bounded-topology");
    assert_matrix_binding(cargo_mode, "supported", "cargo-free-bounded-topology");
    let surface_ids = &cargo_mode["compatibility_surface_matrix"]["surface_ids"];
    assert!(json_array_contains(surface_ids, "path-workspace-basic"), "{surface_ids:#?}");
    assert!(json_array_contains(surface_ids, "local-path-dependency"), "{surface_ids:#?}");
    assert!(json_array_contains(surface_ids, "workspace-inheritance"), "{surface_ids:#?}");
    assert!(json_array_contains(surface_ids, "source-closure-digest"), "{surface_ids:#?}");
    assert!(json_array_contains(surface_ids, "unit-graph-facts"), "{surface_ids:#?}");
    let digest = receipt
        .pointer("/source_closure/sources/0/source_digest/value")
        .and_then(Value::as_str)
        .unwrap_or_default();
    assert_eq!(digest.len(), BLAKE3_HEX_BYTES, "source digest should be BLAKE3-bound: {stdout}");
    assert_eq!(receipt["native_unit_graph_planning"]["ready"], true, "unit graph should be ready: {stdout}");
}

#[test]
fn representative_rust_plan_receipt_is_bounded_success_or_blocker_without_cargo_fallback() {
    let fixture = tempfile::tempdir().unwrap();
    let shim_dir = tempfile::tempdir().unwrap();
    write_representative_workspace(fixture.path());
    let shim = shim_dir.path().join("cargo");
    std::fs::write(&shim, FAILING_CARGO_SHIM).unwrap();
    make_executable(&shim);

    let output = mantle_cmd()
        .arg("--json")
        .arg("rust-plan")
        .arg("--root")
        .arg(fixture.path())
        .arg("--cargo")
        .arg(&shim)
        .arg("--no-cargo-oracle")
        .output()
        .expect("mantle rust-plan should execute");
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);

    assert!(output.status.success(), "stdout:\n{stdout}\nstderr:\n{stderr}");
    assert!(!stderr.contains("cargo must not be invoked"), "rust-plan fell back to Cargo: {stderr}");
    let receipt: Value = serde_json::from_str(&stdout).expect("rust-plan JSON receipt");
    let cargo_mode = receipt.get("cargo_mode").expect("cargo_mode exists");
    let class = cargo_mode["compatibility_class"].as_str().unwrap_or_default();
    assert!(
        class == "cargo-free-bounded-topology" || class == "blocked-unsupported-surface",
        "unexpected compatibility class `{class}` in {stdout}"
    );
    let expected_status = if class == "cargo-free-bounded-topology" {
        "supported"
    } else {
        "blocked"
    };
    assert_matrix_binding(cargo_mode, expected_status, class);
    let matrix = &cargo_mode["compatibility_surface_matrix"];
    if expected_status == "blocked" {
        assert!(json_array_contains(&matrix["surface_ids"], "blocked-unsupported-surface"), "{matrix:#?}");
    }
}

#[cfg(unix)]
fn make_executable(path: &Path) {
    use std::os::unix::fs::PermissionsExt;
    let mut permissions = std::fs::metadata(path).unwrap().permissions();
    permissions.set_mode(EXECUTABLE_MODE);
    std::fs::set_permissions(path, permissions).unwrap();
}

#[cfg(not(unix))]
fn make_executable(_path: &Path) {}
