#!/usr/bin/env python3
"""Record source preparation, never authorize proof execution or import artifacts.

The JSONL protocol retains the original process/phase and publication graph. In
particular, a parent's generated text is NOT converted to literal recipe source.
Linux x86-64 only; the tracee is always a new, disposable process tree.
"""
import argparse
import ctypes
import errno
import json
import os
import pathlib
import signal
import stat
import struct
import subprocess
import sys

SCHEMA = "mantle-source-preparation-trace-v1"
PTRACE_TRACEME = 0
PTRACE_PEEKDATA = 2
PTRACE_SYSCALL = 24
PTRACE_SETOPTIONS = 0x4200
PTRACE_GETEVENTMSG = 0x4201
PTRACE_GET_SYSCALL_INFO = 0x420E
OPTIONS = 0x1 | 0x2 | 0x4 | 0x8 | 0x10 | 0x40 | 0x100000
WALL = 0x40000000
MAX_STRING = 1024 * 1024
MAX_VECTOR = 65536
MAX_IO = 16 * 1024 * 1024
MAX_FILE = 1024 * 1024 * 1024
AT_FDCWD = -100
LIBC = ctypes.CDLL(None, use_errno=True)
LIBC.ptrace.restype = ctypes.c_long


class TraceError(Exception):
    pass


def ptrace(request, pid, address=0, data=0):
    ctypes.set_errno(0)
    result = LIBC.ptrace(ctypes.c_uint(request), ctypes.c_int(pid),
                         ctypes.c_void_p(address), ctypes.c_void_p(data))
    error = ctypes.get_errno()
    if result == -1 and error:
        raise OSError(error, os.strerror(error))
    return result


def signed(value):
    return ctypes.c_int64(value).value


def memory(pid, address, count):
    if count < 0 or count > MAX_IO:
        raise TraceError(f"trace memory request exceeds bound: {count}")
    result = bytearray()
    while len(result) < count:
        word = ptrace(PTRACE_PEEKDATA, pid, address + len(result))
        result.extend((word & ((1 << 64) - 1)).to_bytes(8, "little"))
    return bytes(result[:count])


def cstring(pid, address):
    if not address:
        return b""
    result = bytearray()
    while len(result) < MAX_STRING:
        word = memory(pid, address + len(result), 8)
        end = word.find(b"\0")
        if end >= 0:
            return bytes(result + word[:end])
        result.extend(word)
    raise TraceError("tracee string exceeds bound")


def vector(pid, address):
    if not address:
        return []
    result = []
    for index in range(MAX_VECTOR):
        pointer = int.from_bytes(memory(pid, address + index * 8, 8), "little")
        if not pointer:
            return result
        result.append(cstring(pid, pointer))
    raise TraceError("tracee argv/environment exceeds bound")


def encoded(value):
    """Lossless kernel byte representation; a UTF-8 view is diagnostic only."""
    return {"hex": value.hex(), "utf8": value.decode("utf-8", errors="replace")}


def syscall_info(pid):
    buffer = ctypes.create_string_buffer(128)
    length = ptrace(PTRACE_GET_SYSCALL_INFO, pid, len(buffer), ctypes.addressof(buffer))
    if length < 24:
        raise TraceError("kernel did not return complete syscall information")
    raw = buffer.raw
    if struct.unpack_from("<I", raw, 4)[0] != 0xC000003E:
        raise TraceError("source preparation requires Linux x86-64 syscall ABI")
    if raw[0] == 1:
        return ("entry", struct.unpack_from("<Q", raw, 24)[0],
                struct.unpack_from("<6Q", raw, 32))
    if raw[0] == 2:
        return ("exit", struct.unpack_from("<q", raw, 24)[0], None)
    raise TraceError(f"unexpected ptrace syscall information operation {raw[0]}")


def mapping(values):
    result = {}
    for value in values:
        role, separator, path = value.partition("=")
        if not separator or not role or role in result:
            raise TraceError(f"invalid or duplicate role mapping: {value}")
        result[role] = os.path.realpath(path)
    return result


class Recorder:
    def __init__(self, args):
        self.args = args
        self.root = pathlib.Path(args.output)
        self.root.mkdir(parents=False, exist_ok=False)
        self.journal = (self.root / "trace.jsonl").open("x", encoding="utf-8")
        self.bytes = 0
        self.sequence = 0
        self.processes = {}
        self.active = set()
        self.entries = {}
        self.next_exec = 0
        self.next_publication = 0
        self.sources = mapping(args.source)
        self.artifacts = mapping(args.artifact)
        self.versions = {}
        self.hashes = {}
        self.channels = {}
        self.command_status = None
        self.root_pid = None
        self.emit("header", schema=SCHEMA, boundary=args.boundary,
                  command=[encoded(os.fsencode(arg)) for arg in args.command],
                  sources=self.sources, preparation_artifacts=self.artifacts,
                  provenance=args.provenance,
                  warning="Preparation observations are not proof execution authority; no generated bytes are recipe source")

    def emit(self, kind, pid=None, durable=False, **fields):
        self.sequence += 1
        event = {"sequence": self.sequence, "kind": kind, **fields}
        if pid is not None:
            process = self.processes[pid]
            event.update(pid=pid, parent_pid=process["parent"],
                         exec_id=process["exec"], phase_id=self.phase_id(pid))
        line = json.dumps(event, sort_keys=True, separators=(",", ":")) + "\n"
        size = len(line.encode("utf-8"))
        if self.bytes + size > self.args.trace_bytes_max:
            raise TraceError("preparation trace exceeds explicit byte bound")
        self.journal.write(line)
        self.journal.flush()
        self.bytes += size
        if durable:
            os.fsync(self.journal.fileno())
        return event["sequence"]

    def phase_id(self, pid):
        process = self.processes[pid]
        return f'{process["exec"]}/phase-{process["phase"]:08d}'

    def boundary(self, pid, reason):
        previous = self.phase_id(pid)
        self.processes[pid]["phase"] += 1
        self.emit("phase", pid, previous_phase=previous, reason=reason)

    def digest(self, data=None, path=None, key=None):
        if key is not None and key in self.hashes:
            return self.hashes[key]
        command = [self.args.hasher, "--no-names"]
        if path is not None:
            command.extend(["--", path])
        result = subprocess.run(command, input=data, stdout=subprocess.PIPE,
                                stderr=subprocess.PIPE, check=False)
        digest = result.stdout.strip().decode("ascii", errors="strict")
        if result.returncode or len(digest) != 64 or any(c not in "0123456789abcdef" for c in digest):
            raise TraceError(f"preparation content hasher failed: {result.stderr!r}")
        if key is not None:
            self.hashes[key] = digest
        return digest

    def source_reference(self, path):
        for namespace, paths in (("source", self.sources), ("preparation-artifact", self.artifacts)):
            for role, root in paths.items():
                if path == root:
                    return {"kind": namespace, "role": role, "path": ""}
                if path.startswith(root + os.sep) and os.path.isdir(root):
                    return {"kind": namespace, "role": role, "path": os.path.relpath(path, root)}
        return None

    def snapshot(self, path, display=None):
        metadata = os.stat(path)
        display = display if display is not None else os.path.realpath(path)
        result = {"path": display, "device": metadata.st_dev, "inode": metadata.st_ino,
                  "bytes": metadata.st_size, "mode": stat.S_IMODE(metadata.st_mode)}
        if stat.S_ISREG(metadata.st_mode):
            if metadata.st_size > self.args.file_bytes_max:
                raise TraceError(f"observed regular file exceeds byte bound: {display}")
            key = (metadata.st_dev, metadata.st_ino, metadata.st_size,
                   metadata.st_mtime_ns, metadata.st_ctime_ns)
            result.update(kind="file", digest_blake3=self.digest(path=path, key=key))
            after = os.stat(path)
            if (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns, after.st_ctime_ns) != key:
                raise TraceError(f"file changed while snapshotting: {display}")
        elif stat.S_ISDIR(metadata.st_mode):
            result.update(kind="directory", entries=sorted(os.listdir(path)))
        elif stat.S_ISFIFO(metadata.st_mode):
            result.update(kind="pipe", channel=f"pipe:{metadata.st_dev}:{metadata.st_ino}")
        elif stat.S_ISCHR(metadata.st_mode):
            result.update(kind="character-device", device_number=metadata.st_rdev)
        else:
            raise TraceError(f"unsupported observed file kind at {display}")
        result["initial_reference"] = self.source_reference(display)
        version = self.versions.get(display)
        if version is not None and version["identity"].get("digest_blake3") == result.get("digest_blake3"):
            result["publication_id"] = version["publication_id"]
        return result

    def fd_path(self, pid, fd):
        proc = f"/proc/{pid}/fd/{fd}"
        return proc, os.readlink(proc)

    def fd_snapshot(self, pid, fd):
        proc, target = self.fd_path(pid, fd)
        return self.snapshot(proc, target)

    def resolved_path(self, pid, raw, dirfd=AT_FDCWD):
        if raw.startswith(b"/"):
            return os.path.normpath(os.fsdecode(raw))
        if dirfd == AT_FDCWD:
            base = os.readlink(f"/proc/{pid}/cwd")
        else:
            _, base = self.fd_path(pid, dirfd)
        return os.path.normpath(os.path.join(base, os.fsdecode(raw)))

    def publication(self, pid, fd, reason):
        process = self.processes[pid]
        if fd not in process["dirty"] and fd not in process["mapped_dirty"]:
            return
        try:
            identity = self.fd_snapshot(pid, fd)
        except OSError as error:
            raise TraceError(f"cannot preserve dirty fd {pid}/{fd}: {error}") from error
        if identity["kind"] != "file":
            process["dirty"].discard(fd)
            return
        self.next_publication += 1
        publication = f"{self.args.boundary}/publication-{self.next_publication:09d}"
        self.emit("file_publish", pid, durable=True, publication_id=publication,
                  identity=identity, reason=reason)
        self.versions[identity["path"]] = {"publication_id": publication, "identity": identity}
        process["dirty"].discard(fd)
        process["mapped_dirty"].discard(fd)
        self.boundary(pid, "file-publication")

    def record_read(self, pid, fd, operation):
        self.boundary(pid, "input-consumption")
        identity = self.fd_snapshot(pid, fd)
        key = (fd, identity.get("digest_blake3"), identity.get("publication_id"), identity["kind"])
        if key not in self.processes[pid]["reads"]:
            self.emit("file_read", pid, fd=fd, operation=operation, identity=identity)
            self.processes[pid]["reads"].add(key)
        return identity

    def io_data(self, pid, number, args, count):
        if number in (19, 20, 295, 296, 327, 328):
            if args[2] > MAX_VECTOR:
                raise TraceError("I/O vector exceeds bound")
            result = bytearray()
            for index in range(args[2]):
                base, length = struct.unpack("<QQ", memory(pid, args[1] + 16 * index, 16))
                take = min(length, count - len(result))
                if take:
                    result.extend(memory(pid, base, take))
                if len(result) == count:
                    break
            if len(result) != count:
                raise TraceError("I/O vector shorter than observed syscall result")
            return bytes(result)
        return memory(pid, args[1], count)

    def channel_io(self, pid, fd, direction, data):
        identity = self.fd_snapshot(pid, fd)
        if identity["kind"] != "pipe":
            return
        channel = identity["channel"]
        offsets = self.channels.setdefault(channel, {"write": 0, "read": 0})
        offset = offsets[direction]
        offsets[direction] += len(data)
        self.emit("channel_" + direction, pid, channel=channel, fd=fd,
                  offset=offset, bytes=len(data), digest_blake3=self.digest(data=data),
                  # Bytes are diagnostics only, never promoted to recipe text.
                  observed_bytes=encoded(data) if len(data) <= self.args.diagnostic_bytes_max else None)
        self.boundary(pid, "channel-" + direction)

    def entry(self, pid, number, args):
        event = {"number": number, "args": args}
        self.entries[pid] = event
        process = self.processes[pid]
        # Preserve every entry, including metadata/negative probes and process
        # operations not interpreted below. Expansion must reject unknown effects
        # rather than claiming this numeric diagnostic is a declaration.
        self.emit("syscall_entry", pid, syscall=number, arguments=list(args))
        if number in (59, 322):
            for fd in list(process["dirty"] | process["mapped_dirty"]):
                self.publication(pid, fd, "before-exec")
            index = 0 if number == 59 else 1
            event.update(raw_executable=cstring(pid, args[index]),
                         argv=vector(pid, args[index + 1]),
                         environment=vector(pid, args[index + 2]))
        elif number in (0, 17, 19, 295, 327, 78, 217):
            # A read from a file this phase wrote is a publication barrier.
            self.publication(pid, args[0], "read-after-write")
            event["read_identity"] = self.record_read(pid, args[0], number)
        elif number == 9 and signed(args[4]) >= 0:
            self.publication(pid, args[4], "mmap-after-write")
            event["read_identity"] = self.record_read(pid, args[4], number)
            if args[2] & 2 and args[3] & 1:
                process["mapped_dirty"].add(args[4])
        elif number in (1, 18, 20, 296, 328):
            event["write_identity"] = self.fd_snapshot(pid, args[0])
            # Capture write bytes before the tracee can overwrite its buffer.
            if number in (20, 296, 328):
                if args[2] > MAX_VECTOR:
                    raise TraceError("write vector count exceeds bound")
                total = sum(struct.unpack("<QQ", memory(pid, args[1] + 16 * i, 16))[1]
                            for i in range(args[2]))
            else:
                total = args[2]
            if total > MAX_IO:
                raise TraceError("write syscall exceeds trace memory bound")
            event["write_bytes"] = self.io_data(pid, number, args, total)
        elif number in (3, 74, 75):
            self.publication(pid, args[0], {3: "close", 74: "fsync", 75: "fdatasync"}[number])
        elif number in (2, 85, 257, 437):
            index = 1 if number in (257, 437) else 0
            raw = cstring(pid, args[index])
            dirfd = signed(args[0]) if index else AT_FDCWD
            flags = (struct.unpack("<Q", memory(pid, args[2], 8))[0] if number == 437
                     else args[index + 1] if number != 85 else os.O_CREAT | os.O_TRUNC | os.O_WRONLY)
            event.update(path=self.resolved_path(pid, raw, dirfd), flags=flags)
            # Preserve the old version before O_TRUNC destroys it.
            if flags & os.O_TRUNC:
                try:
                    old = self.snapshot(event["path"])
                except FileNotFoundError:
                    old = None
                self.emit("truncate_intent", pid, path=event["path"], previous=old)
        elif number in (82, 264, 316):
            if number == 82:
                source = self.resolved_path(pid, cstring(pid, args[0]))
                target = self.resolved_path(pid, cstring(pid, args[1]))
            else:
                source = self.resolved_path(pid, cstring(pid, args[1]), signed(args[0]))
                target = self.resolved_path(pid, cstring(pid, args[3]), signed(args[2]))
            event.update(source=source, target=target)
        elif number in (87, 263):
            path = self.resolved_path(pid, cstring(pid, args[1] if number == 263 else args[0]),
                                      signed(args[0]) if number == 263 else AT_FDCWD)
            event["path"] = path
            try:
                event["previous"] = self.snapshot(path)
            except FileNotFoundError:
                event["previous"] = None
        elif number in (40, 275, 276, 278, 326):
            event["transfer_unsupported"] = True
        elif number in (76, 77, 285, 26):
            self.emit("mutation_intent", pid, syscall=number, arguments=list(args))
        elif number in (41, 42, 43, 44, 45, 46, 47, 49, 50, 53, 288):
            raise TraceError(f"network/socket syscall {number} during offline source preparation")
        elif number in (60, 231):
            for fd in list(process["dirty"] | process["mapped_dirty"]):
                self.publication(pid, fd, "process-exit")
            self.emit("exit_intent", pid, status=args[0])

    def returned(self, pid, result):
        event = self.entries.pop(pid, None)
        if event is None:
            return  # A newly followed child may start at its clone syscall exit.
        number, args = event["number"], event["args"]
        process = self.processes[pid]
        self.emit("syscall_exit", pid, syscall=number, result=result)
        if event.get("transfer_unsupported") and result > 0:
            raise TraceError(f"successful unsupported zero-copy transfer syscall {number}; trace retained, no recipe accepted")
        if number in (2, 85, 257, 437):
            self.emit("open", pid, syscall=number, path=event["path"], flags=event["flags"], result=result)
            if result >= 0 and event["flags"] & (os.O_TRUNC | os.O_CREAT):
                process["dirty"].add(result)
        elif number in (0, 17, 19, 295, 327) and result > 0:
            if event["read_identity"]["kind"] == "pipe":
                data = self.io_data(pid, number, args, result)
                self.channel_io(pid, args[0], "read", data)
        elif number in (1, 18, 20, 296, 328) and result > 0:
            if event["write_identity"]["kind"] == "pipe":
                self.channel_io(pid, args[0], "write", event["write_bytes"][:result])
            elif event["write_identity"]["kind"] == "file":
                process["dirty"].add(args[0])
            elif event["write_identity"]["kind"] != "character-device":
                raise TraceError("unsupported write destination")
        elif number in (82, 264, 316):
            self.emit("rename", pid, source=event["source"], target=event["target"], result=result)
            if result == 0:
                previous = self.versions.pop(event["source"], None)
                if previous is not None:
                    self.versions[event["target"]] = previous
                self.boundary(pid, "rename-publication")
        elif number in (87, 263):
            self.emit("unlink", pid, path=event["path"], previous=event["previous"], result=result)
            if result == 0:
                self.versions.pop(event["path"], None)
        elif number in (76, 77, 285, 26):
            self.emit("mutation", pid, syscall=number, arguments=list(args), result=result)
            if result == 0 and number in (77, 285):
                process["dirty"].add(args[0])
        elif number in (32, 33, 292) and result >= 0:
            if args[0] in process["dirty"]:
                process["dirty"].add(result)
            if args[0] in process["mapped_dirty"]:
                process["mapped_dirty"].add(result)

    def register(self, pid, parent):
        inherited = self.processes.get(parent)
        self.processes[pid] = {
            "parent": parent,
            "exec": inherited["exec"] if inherited else f"{self.args.boundary}/pre-exec-{pid}",
            "phase": 0,
            "dirty": set(inherited["dirty"]) if inherited else set(),
            "mapped_dirty": set(inherited["mapped_dirty"]) if inherited else set(),
            "reads": set(),
        }
        self.active.add(pid)

    def executed(self, pid):
        event = self.entries.get(pid)
        if event is None or event["number"] not in (59, 322):
            raise TraceError("exec event has no observed exec syscall entry")
        # Successful exec closes CLOEXEC descriptors; publish before losing them.
        process = self.processes[pid]
        if process["dirty"]:
            raise TraceError("dirty files remained open across exec; explicit earlier publication required")
        self.next_exec += 1
        process["exec"] = f"{self.args.boundary}/exec-{self.next_exec:08d}"
        process["phase"] = 0
        process["reads"].clear()
        actual = self.snapshot(f"/proc/{pid}/exe", os.readlink(f"/proc/{pid}/exe"))
        self.emit("exec", pid, durable=True, executable=actual,
                  requested_executable=encoded(event["raw_executable"]),
                  argv=[encoded(arg) for arg in event["argv"]],
                  environment=[encoded(arg) for arg in event["environment"]],
                  cwd=os.readlink(f"/proc/{pid}/cwd"))
        descriptors = {}
        for name in sorted(os.listdir(f"/proc/{pid}/fd"), key=int):
            fd = int(name)
            descriptors[name] = self.fd_snapshot(pid, fd)
        self.emit("exec_descriptors", pid, descriptors=descriptors)

    def run(self):
        child = os.fork()
        if child == 0:
            try:
                os.setsid()
                ptrace(PTRACE_TRACEME, 0)
                os.kill(os.getpid(), signal.SIGSTOP)
                os.execvpe(self.args.command[0], self.args.command, os.environ.copy())
            except BaseException as error:
                os.write(2, f"preparation child failed: {error}\n".encode())
                os._exit(127)
        self.root_pid = child
        self.register(child, None)
        waited, status = os.waitpid(child, 0)
        if waited != child or not os.WIFSTOPPED(status):
            raise TraceError("preparation child did not stop before first exec")
        ptrace(PTRACE_SETOPTIONS, child, 0, OPTIONS)
        ptrace(PTRACE_SYSCALL, child)
        while self.active:
            pid, status = os.waitpid(-1, WALL)
            if os.WIFEXITED(status) or os.WIFSIGNALED(status):
                code = os.WEXITSTATUS(status) if os.WIFEXITED(status) else None
                death = os.WTERMSIG(status) if os.WIFSIGNALED(status) else None
                self.emit("exit", pid, durable=True, exit_code=code, signal=death)
                self.active.discard(pid)
                self.entries.pop(pid, None)
                if pid == self.root_pid:
                    self.command_status = code if code is not None else 128 + death
                continue
            if not os.WIFSTOPPED(status):
                raise TraceError("unrecognized tracee wait status")
            stopped_signal = os.WSTOPSIG(status)
            event = status >> 16
            if event in (1, 2, 3):
                message = ctypes.c_ulonglong()
                ptrace(PTRACE_GETEVENTMSG, pid, 0, ctypes.addressof(message))
                descendant = message.value
                self.register(descendant, pid)
                self.emit("fork_continuation", descendant, inherited_exec=self.processes[pid]["exec"],
                          inherited_phase=self.phase_id(pid))
                self.emit("spawn", pid, durable=True, child_pid=descendant, clone_kind=event)
                self.boundary(pid, "child-creation")
            elif event == 4:
                self.executed(pid)
            elif event == 6:
                # The process is still alive here; preserve descriptors even for
                # fatal signals that bypassed exit/exit_group syscall entry.
                process = self.processes[pid]
                for fd in list(process["dirty"] | process["mapped_dirty"]):
                    self.publication(pid, fd, "ptrace-exit")
            elif stopped_signal == signal.SIGTRAP | 0x80:
                info, value, arguments = syscall_info(pid)
                if info == "entry":
                    self.entry(pid, value, arguments)
                else:
                    self.returned(pid, value)
            elif stopped_signal not in (signal.SIGSTOP, signal.SIGTRAP):
                self.emit("signal", pid, signal=stopped_signal)
                ptrace(PTRACE_SYSCALL, pid, 0, stopped_signal)
                continue
            ptrace(PTRACE_SYSCALL, pid)
        self.emit("complete", durable=True, command_exit_code=self.command_status,
                  exec_count=self.next_exec, publication_count=self.next_publication)
        if self.command_status:
            raise TraceError(f"source preparation command exited {self.command_status}; failed trace retained")

    def abort(self, error):
        # Only descendants created and registered by this invocation are killed.
        for pid in list(self.active):
            try:
                os.kill(pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
        while self.active:
            try:
                pid, status = os.waitpid(-1, WALL)
            except ChildProcessError:
                break
            if os.WIFEXITED(status) or os.WIFSIGNALED(status):
                self.active.discard(pid)
            elif os.WIFSTOPPED(status):
                try:
                    ptrace(PTRACE_SYSCALL, pid, 0, signal.SIGKILL)
                except ProcessLookupError:
                    pass
        # A reserved separate failure artifact survives journal limit exhaustion.
        with (self.root / "failure.json").open("x", encoding="utf-8") as output:
            json.dump({"schema": SCHEMA, "error": str(error), "last_sequence": self.sequence,
                       "trace_bytes": self.bytes, "accepted_recipe": False}, output, sort_keys=True)
            output.write("\n")
            output.flush()
            os.fsync(output.fileno())
        self.journal.flush()
        os.fsync(self.journal.fileno())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("operation", choices=["record"])
    parser.add_argument("--output", required=True)
    parser.add_argument("--boundary", required=True)
    parser.add_argument("--source", action="append", default=[])
    parser.add_argument("--artifact", action="append", default=[])
    parser.add_argument("--provenance", required=True)
    parser.add_argument("--hasher", default="b3sum")
    parser.add_argument("--trace-bytes-max", type=int, default=256 * 1024 * 1024)
    parser.add_argument("--file-bytes-max", type=int, default=MAX_FILE)
    parser.add_argument("--diagnostic-bytes-max", type=int, default=4096)
    try:
        separator = sys.argv.index("--")
    except ValueError:
        parser.error("separate preparation options and command with --")
    args = parser.parse_args(sys.argv[1:separator])
    args.command = sys.argv[separator + 1:]
    if not args.command or not args.boundary or "/" in args.boundary or not args.provenance:
        parser.error("nonempty command/provenance and one-component boundary are required")
    if not sys.platform.startswith("linux") or os.uname().machine != "x86_64":
        parser.error("preparation tracing requires Linux x86-64")
    if args.trace_bytes_max <= 0 or args.file_bytes_max <= 0 or args.diagnostic_bytes_max < 0:
        parser.error("invalid preparation resource bounds")
    recorder = None
    try:
        recorder = Recorder(args)
        recorder.run()
    except BaseException as error:
        if recorder is not None:
            recorder.abort(error)
        print(f"source preparation failed: {error}", file=sys.stderr)
        return 1
    finally:
        if recorder is not None:
            recorder.journal.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
